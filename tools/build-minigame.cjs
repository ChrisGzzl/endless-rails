"use strict";
// Packs the game module graph (src/main.js, the same entry as index.html) into a single
// script for mini-game runtimes (WeChat mini-game, TapTap minigame).
// Why a bundle: mini-game runtimes load CommonJS, not browser ES modules, and
// have no <script> tags - the ESM module graph must be flattened ahead of time.
//
// Usage: node tools/build-minigame.cjs [outFile]
//   default out: minigame/game-bundle.js
//
// The packer reuses the test harness's execution model: imports are read from
// the real sources, import/export syntax is stripped, and the modules are
// concatenated in the browser's depth-first order so every stripped import
// resolves against the top-level bindings of the modules evaluated before it.
// This is exactly how tests/test-harness.cjs evaluates the same graph.

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const projectRoot = path.resolve(__dirname, "..");
const entryFile = path.resolve(projectRoot, "src/main.js");

function parseModule(file) {
  const src = fs.readFileSync(file, "utf8");
  const imports = [];
  for (const m of src.matchAll(/^import\s*["']([^"']+)["']\s*;.*$/gm)) imports.push({ specifier: m[1], names: [] });
  for (const m of src.matchAll(/^import\s*\{([^}]*)\}\s*from\s*["']([^"']+)["']\s*;.*$/gm)) imports.push({ specifier: m[2] });
  return { file, src, imports };
}

const modules = new Map();
const order = [];
function visit(file) {
  if (modules.has(file)) return;
  const mod = parseModule(file);
  modules.set(file, mod);
  for (const decl of mod.imports) {
    assert.ok(decl.specifier.startsWith("."), "only relative imports are supported: " + file);
    visit(path.resolve(path.dirname(file), decl.specifier));
  }
  order.push(mod);
}
visit(entryFile);

function strip(mod) {
  return mod.src
    .replace(/^import\s*["'][^"']+["']\s*;.*$/gm, "")
    .replace(/^import\s*\{[^}]*\}\s*from\s*["'][^"']+["']\s*;.*$/gm, "")
    .replace(/^export\s*\{[^}]*\}\s*;.*$/gm, "")
    .replace(/^export\s+(?=(?:async\s+)?(?:const|let|var|function\s*\*?|class))/gm, "")
    // The mini-game runtime wraps this bundle as a CommonJS module, so a real
    // `module` is in scope and UMD core modules would take their module.exports
    // branch - which nothing then reads. Point those writes at a dead global so
    // every module keeps its window mount (the game.js shim provides window).
    .replace(/module\.exports/g, "globalThis.__bundledExports");
}

const chunks = [
  "/* Generated by tools/build-minigame.cjs from src/main.js - do not edit by hand.",
  "   Modules are concatenated in depth-first evaluation order; stripped imports",
  "   resolve against the top-level bindings of earlier modules (the same model",
  "   tests/test-harness.cjs uses). Core UMD modules keep their window mounts:",
  "   minigame/game.js redirects window to the mini-game global before this runs. */",
  '"use strict";',
];
for (const mod of order) {
  const id = path.relative(projectRoot, mod.file).replace(/\\/g, "/");
  chunks.push(`\n/* ---- ${id} ---- */\n${strip(mod)}`);
}

const outPath = path.resolve(projectRoot, process.argv[2] || "minigame/game-bundle.js");
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, chunks.join("\n") + "\n");
console.log("wrote " + outPath + " (" + order.length + " modules)");
